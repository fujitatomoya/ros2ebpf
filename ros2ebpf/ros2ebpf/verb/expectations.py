import sys
import time

import yaml

from ros2ebpf.api import compute_rates
from ros2ebpf.api import ConnectError
from ros2ebpf.api import resolve_targets
from ros2ebpf.api import RpcError
from ros2ebpf.verb import VerbExtension


class ExpectationsVerb(VerbExtension):
    """Capture current publish rates into expectations.yaml, or show the current file."""

    def add_arguments(self, parser, cli_name):
        sub = parser.add_subparsers(dest='action', required=True)
        cap = sub.add_parser('capture', help='Observe rates for a while and write expectations.yaml')
        cap.add_argument('--duration', type=float, default=60.0, help='Seconds to observe (default: %(default)s)')
        cap.add_argument('--output', '-o', default='expectations.yaml',
                         help='Output file (default: %(default)s); - for stdout')
        cap.add_argument('--min-hz', type=float, default=0.1, help='Skip topics below this rate (default: %(default)s)')
        cap.add_argument('--round', type=int, default=1, help='Decimal places (default: %(default)s)')
        cap.add_argument('--takers', action='store_true', help='Also record the number of taking targets per topic')
        show = sub.add_parser('show', help='Print the expectations file')
        show.add_argument('--file', default='/etc/ros2ebpf/expectations.yaml')

    def main(self, *, args):
        if args.action == 'show':
            try:
                with open(args.file) as f:
                    print(f.read(), end='')
            except OSError as e:
                print(f'error: {e}', file=sys.stderr)
                return 2
            return 0

        try:
            clients = resolve_targets(args)
        except ConnectError as e:
            print(f'error: {e}', file=sys.stderr)
            return 2
        try:
            first = {c.name: c.call('snapshot') for c in clients}
            print(f'observing {len(clients)} target(s) for {args.duration:.0f} s ...', file=sys.stderr)
            time.sleep(args.duration)
            second = {c.name: c.call('snapshot') for c in clients}
        except (ConnectError, RpcError) as e:
            print(f'error: {e}', file=sys.stderr)
            return 1
        finally:
            for c in clients:
                c.close()

        hz = {}
        takers = {}
        for name in first:
            for r in compute_rates(first[name], second[name]):
                if r['kind'] == 'publisher':
                    hz[r['name']] = hz.get(r['name'], 0.0) + r['rate']
                elif r['kind'] == 'subscription' and r['rate'] > 0:
                    takers.setdefault(r['name'], set()).add(name)
        doc = {}
        for topic in sorted(hz):
            rate = round(hz[topic], args.round)
            if rate < args.min_hz:
                continue
            if args.takers and topic in takers:
                doc[topic] = {'hz': rate, 'takers': len(takers[topic])}
            else:
                doc[topic] = rate
        text = ('# generated by `ros2 ebpf expectations capture` on '
                f'{time.strftime("%Y-%m-%d %H:%M:%S")} over {args.duration:.0f} s\n'
                + yaml.safe_dump(doc, sort_keys=True, default_flow_style=None))
        if args.output == '-':
            print(text, end='')
        else:
            with open(args.output, 'w') as f:
                f.write(text)
            print(f'wrote {len(doc)} topics to {args.output}', file=sys.stderr)
        return 0
